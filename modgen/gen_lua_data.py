"""Write lua/LivingWastelandLua/scripts/lw/data.lua from the content packs, so the Lua side knows our outlaws, recruits and dome papers.

  python gen_lua_data.py
"""
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "lua", "LivingWastelandLua", "scripts", "lw", "data.lua")


def load(n):
    return json.load(open(os.path.join(HERE, "content", n), encoding="utf-8"))


def q(s):
    return '"' + str(s).replace("\\", "\\\\").replace('"', '\\"') + '"'


PREFIX_GROUP = {"qc": "Work", "iq": "Investigation", "rc": "Recruit", "hw": "Quiet errand", "de": "Errand", "cr": "Courier",
                "ol": "Bounty", "bd": "Bounty"}


def words(qid):
    parts = qid.split("_")
    group = PREFIX_GROUP.get(parts[0], "Task")
    return group, " ".join(w.capitalize() for w in parts[1:] if w not in ("q",)) or qid


def first(x):
    if isinstance(x, list):
        return x[0] if x else ""
    return x or ""


def journal_entries():
    """Quests and contracts as plain tables for the in-game journal: variable name, title, objectives per stage."""
    import glob
    out = []
    for path in sorted(glob.glob(os.path.join(HERE, "content", "[!_]*.json"))):
        pack = json.load(open(path, encoding="utf-8"))
        for q in pack.get("quests", []) or []:
            group, nice = words(q["id"])
            steps = q.get("steps", [])
            obj = [first(q["offer"].get("accepted", ""))]
            for i in range(len(steps) - 1):      # after step i is done, point at step i+1
                obj.append(first(steps[i].get("after", "")) or first(steps[i + 1].get("say", "")))
            obj.append("Return and report. " + first(q["report"].get("say", ""))[:90])
            out.append({"var": f"Quest {q['id']}", "title": f"{group}: {nice}", "stages": len(steps) + 1,
                        "offer": first(q["offer"].get("say", "")), "objectives": obj,
                        "reward": int(q["report"].get("reward", 0))})
        for c in pack.get("contracts", []) or []:
            group, nice = words(c["id"])
            who = c.get("state", "").replace(" killed by player", "").replace(" imprisoned by player", "")
            out.append({"var": f"Contract {c['id']}", "title": f"Bounty: {who or nice}", "stages": 1,
                        "offer": first(c.get("offer", "")), "objectives": [first(c.get("accepted", "")), "Report back for payment."],
                        "reward": int(c.get("reward", 0))})
    return out


def main():
    lines = ["-- GENERATED by modgen/gen_lua_data.py from the content packs. Do not edit by hand.", "return {"]
    outlaws = []
    for f in ("outlaws.json", "recruits.json"):
        for o in load(f).get("outlaws", []):
            outlaws.append(o)
    lines.append("  outlaws = {")
    for o in outlaws:
        lines.append(f"    {{ name = {q(o['name'])}, faction = {q(o['faction'])}, squad = {q(o['name'] + ' squad')}, bounty = {int(o.get('bounty', 0))} }},")
    lines.append("  },")
    rc = load("recruits.json")
    names = [c["name"] for c in rc["clones"] if c.get("kind") == "character"]
    lines.append("  recruits = {")
    for n in names:
        lines.append(f"    {q(n)},")
    lines.append("  },")
    li = load("lore_items.json")
    lines.append("  domePapers = {")
    for lst in li.get("item_lists", []):
        lines.append(f"    {{ list = {q(lst['name'])}, squad = {q(lst['squads'][0][0])}, items = {{ " + ", ".join(q(i[0]) for i in lst["items"]) + " } },")
    lines.append("  },")
    lines.append("}")
    jl = ["-- GENERATED by modgen/gen_lua_data.py from the content packs. Do not edit by hand.", "return {"]
    for e in journal_entries():
        objs = ", ".join(q(o[:260]) for o in e["objectives"])
        jl.append(f"  {{ var = {q(e['var'])}, title = {q(e['title'])}, stages = {e['stages']}, reward = {e['reward']}, offer = {q(e['offer'][:200])}, objectives = {{ {objs} }} }},")
    jl.append("}")
    open(os.path.join(os.path.dirname(OUT), "quests_data.lua"), "w", encoding="utf-8").write("\n".join(jl) + "\n")
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    open(OUT, "w", encoding="utf-8").write("\n".join(lines) + "\n")
    print("wrote", OUT, len(outlaws), "outlaws", len(names), "recruits")


if __name__ == "__main__":
    main()
