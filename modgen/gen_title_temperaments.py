"""Writes content/x_title_temperaments.json from content/_faction_temperaments.json (Meitou only; design: TITLES_BY_FACTION.md).

    python gen_title_temperaments.py

For each faction and each title it admires, despises or fears:
  * on-sight lines ("nt_" ids, so the Gossip amount slider covers them, like the other title reactions);
  * admires / despises: once per title per faction, one of its people says so and relations change by +3 / -3 ("tm_" ids;
    the helper remembers it was done: TEMPER_ONCE / TEMPER_MARK in meitou_target.py);
  * admires: rarely, once per title per faction, a barman or shopkeeper of that faction gives the holder its gift item;
  * despises: the faction's job givers refuse the holder (the compiler gates every offer on the helper's "despised" condition,
    using the "temperaments" table this pack carries).
Edit _faction_temperaments.json, run this, rebuild. Do not edit the generated JSON by hand.
"""
import json
import os
from detrope import detrope_pack
from contractions import contract_pack

HERE = os.path.dirname(os.path.abspath(__file__))
CONTENT = os.path.join(HERE, "content")

CALM = [{"cond": "DC_IS_SLAVE", "who": "me", "value": 0}, {"cond": "DC_IN_COMBAT", "who": "me", "value": 0}]
BUMP = {"admire": 3, "despise": -3}
# each gifting faction's favour charm (content/trophies.json, worn in the helper's neck slot), handed over with the gift
CHARMS = json.load(open(os.path.join(CONTENT, "_charms.json"), encoding="utf-8"))


def slug(s):
    return "".join(c.lower() if c.isalnum() else "_" for c in s).strip("_")


def fill(lines, title):
    cap = title[:1].upper() + title[1:]
    return [ln.replace("{Title}", cap).replace("{title}", title) for ln in lines]


def main():
    table = json.load(open(os.path.join(CONTENT, "_faction_temperaments.json"), encoding="utf-8"))["factions"]
    titles = {t["id"]: t["name"] for t in json.load(open(os.path.join(CONTENT, "notoriety.json"), encoding="utf-8"))["titles"]}
    # one pack per mod: a faction a mod makes (the Cannibals mod's Gate Folk) is spoken for from that mod, so the base mod needs no other
    packs = {}
    for faction, t in table.items():
        mod = t.get("mod", "LivingWasteland")
        name = "x_title_temperaments" if mod == "LivingWasteland" else "x_title_temperaments_" + mod.replace("LivingWasteland", "").lower()
        pack = packs.setdefault(name, {"pack": name, "mod": mod,
                                       "note": "GENERATED by gen_title_temperaments.py from _faction_temperaments.json (do not edit by hand). Meitou only.",
                                       "temperaments": {}, "title_views": {}, "dialogues": []})
        # what the faction thinks of each title, by title name (the Atlas's faction pages)
        pack["title_views"][faction] = {k: [titles[t] for t in t_.get(k, []) if t in titles] for k, t_ in (("admires", t), ("despises", t), ("fears", t))}
        if t.get("despises"):
            pack["temperaments"][faction] = t["despises"]
        extra = {"packages": t["packages"]} if t.get("packages") else {}   # a faction a mod makes names its own package
        event = t.get("event", "EV_I_SEE_NEUTRAL_SQUAD")   # factions hostile to the player (the Cannibals) speak on enemy sight
        fs = slug(faction)
        for attitude, key in (("admire", "admires"), ("despise", "despises"), ("fear", "fears")):
            for tid in t.get(key, []):
                if tid not in titles:
                    raise SystemExit(f"{faction}: unknown title '{tid}'")
                name = titles[tid]
                said = fill(t[attitude], name)
                pack["dialogues"].append({**extra, "id": f"nt_tm_{fs}_{tid}_{attitude}", "event": event, "player_only": True,
                                          "factions": [faction], "one_at_a_time": True, "chance": 10, "repeat": 3,
                                          "lw_if": [{"title": tid, "who": "target"}], "if": CALM, "lines": [{"say": said}]})
                if attitude in BUMP:
                    pack["dialogues"].append({**extra, "id": f"tm_{fs}_{tid}_{attitude}_once", "event": event, "player_only": True,
                                              "factions": [faction], "one_at_a_time": True, "chance": 30,
                                              "lw_if": [{"title": tid, "who": "target"}, {"not_done": tid, "kind": "bump"}], "if": CALM,
                                              "lines": [{"say": said, "effects": [["DA_AFFECT_RELATIONS", BUMP[attitude]]],
                                                         "lw_do": [{"mark": tid, "kind": "bump"}]}]})
                if attitude == "admire" and t.get("gift"):
                    pack["dialogues"].append({**extra, "id": f"tm_{fs}_{tid}_gift", "event": "EV_I_SEE_NEUTRAL_SQUAD", "player_only": True,
                                              "factions": [faction], "one_at_a_time": True, "chance": 4,
                                              "lw_if": [{"title": tid, "who": "target"}, {"not_done": tid, "kind": "gift"}],
                                              "if": CALM + [{"cond": "DC_IS_A_TRADER", "who": "me", "value": 1}],
                                              "lines": [{"say": fill(t["gift_line"], name),
                                                         "lw_do": [{"gift": t["gift"]}] + ([{"gift": CHARMS[faction]}] if faction in CHARMS else []) + [{"mark": tid, "kind": "gift"}]}]})
    for name, pack in packs.items():
        path = os.path.join(CONTENT, name + ".json")
        with open(path, "w", encoding="utf-8") as fh:
            detrope_pack(pack)                 # the same punchline pass as content/ (detrope.py)
            contract_pack(pack)                # contractions by voice (contractions.py)
            json.dump(pack, fh, indent=1, ensure_ascii=False)
            fh.write("\n")
        print(f"wrote {path}: {len(pack['dialogues'])} dialogues; despise table for {len(pack['temperaments'])} factions")


if __name__ == "__main__":
    main()
