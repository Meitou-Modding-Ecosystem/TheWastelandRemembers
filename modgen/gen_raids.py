"""Writes content/x_raids.json: harassment raids (Meitou only; Raids.cs in the helper).

    python gen_raids.py

A small faction now and then sends a raiding party to lurk near a town of the big one it fights, for two days; no towns change hands.
Gossip follows what really happened: while the party is out, then for five days whether it was caught (the party died or vanished) or
got away. Per raid: a squad cloned from one of the raider's own (so no vanilla patrol is ever taken over), a word swap /LWRAID_r/ naming
the town (one line per candidate town, chosen by the helper's town code), and bar talk / in-town sight lines for each state.
Ids start with "on_" so the Gossip amount slider covers them. Edit RAIDS below, run this, rebuild; do not edit the JSON by hand.
"""
import json
import os
from detrope import detrope_pack
from contractions import contract_pack

HERE = os.path.dirname(os.path.abspath(__file__))
CONTENT = os.path.join(HERE, "content")
TOWN_CHECKS = [{"cond": "DC_IN_A_NON_PLAYER_TOWN", "who": "me", "value": 1}, {"cond": "DC_IN_COMBAT", "who": "me", "value": 0},
               {"cond": "DC_IS_SLAVE", "who": "me", "value": 0}]

RAIDS = [
    {"name": "flotsam", "raider": "Flotsam Ninjas", "squad": "Flotsam raiders", "from": "flotsam patrol", "target": "The Holy Nation",
     "speakers": ["The Holy Nation", "Flotsam Ninjas", "Traders Guild", "Nomads", "Drifters"],
     "out": ["Flotsam raiders in the hills near /T/. The paladins are doubling the patrols.",
             "Ninjas out of the forest again, near /T/. Holy patrols walk in fours now."],
     "caught": ["The Holy Nation caught a Flotsam raiding party near /T/. Nobody walked away.",
                "Paladins hanged Flotsam raiders outside /T/. Okran's justice, they call it."],
     "away": ["Flotsam raiders hit a patrol near /T/ and were gone before the paladins came.",
              "The Flotsam struck near /T/ and vanished into the trees again."]},
    {"name": "antislaver", "raider": "Anti-Slavers", "squad": "Anti-Slaver raiders", "from": "Anti slaver all strong small", "target": "Slave Traders",
     "speakers": ["Anti-Slavers", "Slave Traders", "United Cities", "Traders Guild", "Nomads"],
     "out": ["Anti-Slavers are out near /T/. The slavers are moving their stock at night.",
             "Tinfist's people are in the hills by /T/. The slave caravans are waiting it out."],
     "caught": ["The slavers caught an Anti-Slaver party near /T/. They'll be wearing chains now.",
                "Anti-Slavers tried their luck near /T/. The slavers sold the survivors."],
     "away": ["Anti-Slavers broke a slave caravan near /T/ and got clean away.",
              "Freed slaves walking out of the desert near /T/. Anti-Slaver work."]},
    {"name": "rebels", "raider": "Rebel Farmers", "squad": "Rebel farmer raiders", "from": "empire rebel farmers small", "target": "United Cities",
     "speakers": ["United Cities", "Rebel Farmers", "Traders Guild", "Nomads", "Drifters"],
     "out": ["Rebel farmers are out near /T/. The samurai are nervous.",
             "Peasants with spears near /T/. The nobles call it banditry."],
     "caught": ["Samurai cut down a rebel band near /T/. Heads on poles by the road.",
                "The rebels near /T/ were caught. The nobles call it a lesson."],
     "away": ["Rebel farmers burned a noble's storehouse near /T/ and melted back into the fields.",
              "The rebels hit a patrol near /T/ and were gone by morning."]},
    {"name": "hunters", "raider": "Cannibal Hunters", "squad": "Cannibal hunting party", "from": "cannibal hunter patrol", "target": "Cannibals",
     "speakers": ["Cannibal Hunters", "United Cities", "The Holy Nation", "Traders Guild"],
     "extra_towns": ["Cannibal Capital", "First Village", "Cannibals", "Cannibal Village", "Cannibal Village 2"],
     "out": ["A Cannibal Hunter party went out past /T/. Pray they come back.",
             "The red cloaks are hunting near /T/ again."],
     "caught": ["The cannibals caught a hunting party near /T/. The Bastion is quiet tonight.",
                "Hunters went out near /T/. None came back. Nobody wants to say why."],
     "away": ["The Hunters came back from /T/ with heads on poles. Cannibal heads.",
              "A hunting party cleared the cannibals near /T/. Drinks at the Bastion."]},
]
STATES = (("out", 1), ("caught", 2), ("away", 3))


def towns():
    news = json.load(open(os.path.join(CONTENT, "x_world_news.json"), encoding="utf-8"))
    seen = []
    for w in news["word_swaps"]:
        for ln in w["lines"]:
            if ln.get("wartown") and ln["wartown"] not in seen:
                seen.append(ln["wartown"])
    return seen


def main():
    town_list = towns()
    pack = {"pack": "x_raids", "mod": "LivingWasteland", "meitou_only": True,
            "note": "GENERATED by gen_raids.py (do not edit by hand). Meitou only: harassment raids and the talk about them.",
            "clones": [], "raids": [], "word_swaps": [], "dialogues": []}
    for r in RAIDS:
        key, swap = r["name"], f"LWRAID_{r['name'].upper()}"
        pack["clones"].append({"kind": "squad", "from": r["from"], "name": r["squad"]})
        pack["raids"].append({"name": key, "squad": r["squad"], "target": r["target"], "raider": r["raider"]})
        candidates = list(dict.fromkeys(town_list + r.get("extra_towns", [])))
        pack["word_swaps"].append({"name": swap, "lines": [{"say": t, "raidtown": t, "raid": key} for t in candidates] + [{"say": "the border"}]})
        for state, value in STATES:
            said = [ln.replace("/T/", f"/{swap}/") for ln in r[state]]
            cond = [{"raid": key, "value": value}]
            pack["dialogues"].append({"id": f"on_raid_{key}_{state}_bar", "event": "EV_BAR_TALK", "factions": r["speakers"], "one_at_a_time": True,
                                      "lw_if": cond, "lines": [{"say": said}], "chance": 10, "repeat": 3})
            pack["dialogues"].append({"id": f"on_raid_{key}_{state}_sight", "event": "EV_I_SEE_NEUTRAL_SQUAD", "player_only": True,
                                      "factions": r["speakers"], "one_at_a_time": True, "lw_if": cond, "lines": [{"say": said}],
                                      "chance": 4, "repeat": 2, "if": TOWN_CHECKS})
    path = os.path.join(CONTENT, "x_raids.json")
    with open(path, "w", encoding="utf-8") as fh:
        detrope_pack(pack)                 # the same punchline pass as content/ (detrope.py)
        contract_pack(pack)                # contractions by voice (contractions.py)
        json.dump(pack, fh, indent=1, ensure_ascii=False)
        fh.write("\n")
    print(f"wrote {path}: {len(RAIDS)} raids, {len(pack['dialogues'])} dialogues")


if __name__ == "__main__":
    main()
